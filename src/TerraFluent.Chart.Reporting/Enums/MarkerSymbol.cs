namespace TerraFluent.Chart.Reporting.Enums
{
    /// <summary>
    /// Shape used to render data-point markers on line, spline, area, and scatter series.
    /// </summary>
    public enum MarkerSymbol
    {
        /// <summary>A filled circle (the default).</summary>
        Circle,
        /// <summary>A filled square.</summary>
        Square,
        /// <summary>A filled diamond (rotated square).</summary>
        Diamond,
        /// <summary>A filled upward-pointing triangle.</summary>
        Triangle,
        /// <summary>A filled downward-pointing triangle.</summary>
        TriangleDown
    }
}
